function renderCatcherStudy(path) {
  if (path !== catcherStudyPath) return false;
  app.innerHTML = crumbs([['אדר','#/adar'], ['כיתה י״ב'], ['ספרות','#/adar/literature'], ['התפסן בשדה השיפון',catcherPath], ['חימום']]) +
    `<h1>חימום לפני המבחנים</h1>
     <p class="intro">עני בקול או בכתב על כל שאלה לפני שתפתחי את ההסבר. אם נתקעת, חזרי לסצנה שמופיעה בתשובה.</p>
     <section class="review">
       ${catcherStudyTopics.map(([topic, question, answer]) => `<details>
         <summary>${esc(topic)} — ${esc(question)}</summary><p>${esc(answer)}</p>
       </details>`).join('')}
     </section>
     <section class="question" aria-labelledby="catcher-builder">
       <h2 id="catcher-builder">בני תשובה על הקרוסלה</h2>
       <p>בחרי משפט שמחבר את הסצנה לטענה על ההתבגרות של הולדן.</p>
       <div class="answers" id="catcher-choices">
         <button type="button" class="answer">פיבי עולה לקרוסלה, ומתחיל לרדת גשם.</button>
         <button type="button" class="answer">הולדן נותן לפיבי לנסות לתפוס את הטבעת למרות הסיכון. בכך הוא מאפשר לה להתנסות בעצמה.</button>
         <button type="button" class="answer">הולדן מתבגר, ולכן הוא פותר את כל הקשיים שלו.</button>
       </div>
       <p id="catcher-feedback" class="notice" aria-live="polite" hidden></p>
     </section>
     <div class="actions"><a class="btn primary" href="${catcherPath}">לבחירת מבחן</a></div>`;
  const feedback = document.getElementById('catcher-feedback');
  app.querySelectorAll('#catcher-choices button').forEach((button, index) => {
    button.onclick = () => {
      feedback.hidden = false;
      feedback.textContent = [
        'זה תיאור מדויק של הסצנה. הוסיפי הסבר על הבחירה של הולדן ועל מה שהיא מגלה.',
        'נכון. המשפט מביא פעולה מסוימת ומסביר את משמעותה. זה החיבור בין ראיה לטענה שמחפשים בשאלה פתוחה.',
        'זו מסקנה רחבה מדי. הסצנה מלמדת על שינוי מסוים ביחסו לפיבי, והמשך דרכו נשאר פתוח.',
      ][index];
    };
  });
  return true;
}
